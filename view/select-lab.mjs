// Run against an isolated Profiles lab with twelve fixture agents named Agent 01 through Agent 12.
// Use tests/profiles-lab-setup.sh, then replace its agent profiles before starting the hub.
// Each fixture command prints selected-agent-N and sleeps. The test closes its own session.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import {connectControl} from '../../lib/rex-client.mjs';

const lab=process.env.PROFILES_LAB || '/tmp/rexlab-profiles-select';
assert.match(lab,/^\/tmp\/rexlab-profiles-[^/]+$/);
const socket=`unix://${lab}/rex.sock`;
const env={...process.env,REX_SERVER:socket};
for(const name of ['REX_SESSION','REX_BLOCK','REX_CLIENT']) delete env[name];
const rex=(...args)=>execFileSync('rex',['-S',socket,'--autostart=false',...args],{env,encoding:'utf8'});
const c=await connectControl(`${lab}/rex.sock`);
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const wait=async(label,read)=>{for(let i=0;i<80;i++){const value=await read();if(value)return value;await sleep(150);}throw Error(`Timed out: ${label}`);};
let session;
try {
  const created=await c.call('session.create',{label:'select-picker-lab',initial_windows:[{layout:{block:{flavor:'com.superlogical.terminal.shell',options:{command:['/bin/sh','-c','exec sleep 600'],cwd:`${lab}/repo`,login:false}}}}]});
  session=created.session_id;
  const source=created.initial_windows[0].block_ids[0];
  await c.call('session.attach',{session_id:session,event_scope:'session'});
  const blocks=async()=>(await c.call('session.view',{session_id:session})).windows.flatMap(w=>w.layers.flatMap(l=>l.blocks));
  await c.call('client.action',{action:'lazyrex_profiles_start_agent',origin:'palette',session_id:session,block_id:source});
  const form=await wait('form pane',async()=>(await blocks()).find(b=>b.label?.startsWith('lazyrex-form:')));
  const block=form.block_id;
  await c.call('session.own_block',{session_id:session,block_ids:[block],mode:'take'});
  const resize=(columns,rows)=>c.call('com.superlogical.terminal.resize',{session_id:session,block_id:block,args:{columns,rows}});
  await resize(90,65);
  const screen=()=>rex('capture','-s',session,'-b',block);
  const key=async(...keys)=>{for(const k of keys){rex('send-key','-s',session,'-b',block,k);await sleep(220);}};
  await wait('Profile field',()=>screen().includes('Profile *'));
  await key('ctrl+n','tab');
  const closed=screen();
  await key('enter');
  await wait('open list',()=>screen().includes('✓')&&screen().includes('4 more below'));
  let text=screen();
  for(let i=1;i<=8;i++) assert(text.includes(`Agent ${String(i).padStart(2,'0')}`));
  assert(!text.includes('Agent 09'),'Only eight options appear');
  const unchangedOutside = (before, after) => {
    const a=before.split('\n'), b=after.split('\n');
    const first=b.findIndex(line=>/│.*(?:Agent \d\d|New tab|Split beside)/.test(line));
    const top=first-2;
    const left=b[top]?.indexOf('╭');
    const bottom=b.findIndex((line,i)=>i>top&&line[left]==='╰');
    assert(top>=0&&bottom>top,'Overlay border is visible');
    for(let i=0;i<a.length;i++) if(i<top||i>bottom) assert.equal(b[i]?.trimEnd(),a[i].trimEnd(),`Form row ${i} moved`);
    return {top,bottom,left,width:b[top].indexOf('╮')-left+1};
  };
  const wideBounds=unchangedOutside(closed,text);
  assert.equal(wideBounds.width,20,'Profile width follows its control and labels');
  assert(!text.includes('Filter:'),'An empty filter has no label');
  fs.writeFileSync(`${lab}/select-open.txt`,text);
  fs.writeFileSync(`${lab}/select-open.html`,rex('capture','-s',session,'-b',block,'--format=html'));
  console.log('PASS: Profiles Start form opens eight of twelve choices without moving the form');
  await key('end');
  await wait('last option',()=>screen().includes('Agent 12')&&screen().includes('4 more above'));
  await key('escape');
  assert(!screen().includes('✓')&&screen().includes('Agent 01 ▾'),'Escape keeps the field');
  await key('space');
  const filterBefore=screen();
  const filterOrigin=unchangedOutside(closed,filterBefore);
  await key('1','0');
  await wait('filtered choice',()=>screen().includes('Filter: 10')&&screen().includes('Agent 10'));
  const filtered=screen();
  const filteredOrigin=unchangedOutside(closed,filtered);
  assert.equal(filteredOrigin.top,filterOrigin.top,'Filtering keeps the list origin');
  fs.writeFileSync(`${lab}/select-filtered.txt`,filtered);
  await key('backspace','backspace');
  assert(!screen().includes('Filter:')&&screen().includes('✓'),'Clearing restores the top padding row');
  await key('1','0','enter');
  await wait('picked value',()=>screen().includes('Agent 10 ▾')&&!screen().includes('✓'));
  console.log('PASS: End, Escape, filter, and Enter preserve or commit the correct choice');
  await key('enter','home');
  await wait('first options',()=>screen().includes('Agent 03')&&screen().includes('4 more below'));
  text=screen();
  const hoverLines=text.split('\n');
  const hoverY=hoverLines.findIndex(line=>line.includes('Agent 04'))+1;
  const hoverX=hoverLines[hoverY-1].indexOf('Agent 04')+1;
  await c.call('com.superlogical.terminal.write',{session_id:session,block_id:block,args:{data:`\x1b[<35;${hoverX};${hoverY}M`}});
  await sleep(250);
  fs.writeFileSync(`${lab}/select-hover.txt`,screen());
  fs.writeFileSync(`${lab}/select-hover.html`,rex('capture','-s',session,'-b',block,'--format=html'));
  await c.call('com.superlogical.terminal.write',{session_id:session,block_id:block,args:{data:'\x1b[<35;1;1M'}});
  await key('enter');
  await wait('hover candidate picked after leaving',()=>screen().includes('Agent 04 ▾')&&!screen().includes('✓'));
  console.log('PASS: pointer motion changes the candidate; leaving keeps it for Enter');
  await key('enter','home');
  text=screen();
  const lines=text.split('\n');
  const y=lines.findIndex(line=>line.includes('Agent 03'))+1;
  const x=lines[y-1].indexOf('Agent 03')+1;
  assert(y>0&&x>0);
  await c.call('com.superlogical.terminal.write',{session_id:session,block_id:block,args:{data:`\x1b[<0;${x};${y}M\x1b[<0;${x};${y}m`}});
  await wait('pointer pick',()=>screen().includes('Agent 03 ▾')&&!screen().includes('✓'));
  console.log('PASS: mouse input picks Agent 03');
  await resize(32,20);await sleep(300);
  const shortClosed=screen();
  fs.writeFileSync(`${lab}/select-short-closed.txt`,shortClosed);
  await key('enter','end');
  fs.writeFileSync(`${lab}/select-short-open.txt`,screen());
  await wait('short pane reveals highlight',()=>screen().includes('Agent 12'));
  unchangedOutside(shortClosed,screen());
  fs.writeFileSync(`${lab}/select-narrow.txt`,screen());
  fs.writeFileSync(`${lab}/select-narrow.html`,rex('capture','-s',session,'-b',block,'--format=html'));
  await key('escape');
  await resize(32,16);await sleep(300);
  await key('tab','tab');
  await wait('Placement field',()=>screen().includes('New tab ▾'));
  const placementClosed=screen();
  await key('enter');
  await wait('Placement list',()=>screen().includes('✓')&&screen().includes('Split'));
  const placementOpen=screen();
  assert(!placementOpen.includes('more above')&&!placementOpen.includes('more below'),'All Placement options fit without a hint row');
  assert(!placementOpen.includes('Loading the updated view'),'Populated form has no stale loading status');
  const bounds=unchangedOutside(placementClosed,placementOpen);
  const fieldY=placementClosed.split('\n').findIndex(line=>line.includes('New tab ▾'));
  fs.writeFileSync(`${lab}/select-placement-closed.txt`,placementClosed);
  fs.writeFileSync(`${lab}/select-placement.txt`,placementOpen);
  fs.writeFileSync(`${lab}/select-placement.html`,rex('capture','-s',session,'-b',block,'--format=html'));
  assert(bounds.bottom<fieldY,'Placement list flips above its field');
  // Clicking the field outside the overlay closes it without reopening on release.
  const click=async(x,y)=>c.call('com.superlogical.terminal.write',{session_id:session,block_id:block,args:{data:`\x1b[<0;${x};${y}M\x1b[<0;${x};${y}m`}});
  await click(6,fieldY+1);
  await wait('outside click cancels',()=>!screen().includes('✓')&&screen().includes('New tab ▾'));
  await key('enter');
  await wait('Placement reopens',()=>screen().includes('✓'));
  const splitLines=screen().split('\n');
  const splitY=splitLines.findIndex(line=>line.includes('Split'));
  await click(splitLines[splitY].indexOf('Split')+1,splitY+1);
  await wait('Split picked over covered content',()=>!screen().includes('✓')&&screen().includes('Split beside'));
  console.log('PASS: short pane keeps form rows fixed; Placement flips above; mouse cancels or picks');
  await key('left','shift+tab','shift+tab');
  await resize(90,65);await sleep(300);
  await key('tab','tab','tab','enter');
  const spawned=await wait('selected agent starts',async()=>(await blocks()).find(b=>b.label?.startsWith('lazyrex-spawn:')));
  await wait('selected command output',()=>rex('capture','-s',session,'-b',spawned.block_id).includes('selected-agent-3'));
  console.log('PASS: Start submits Agent 03 through the unchanged Profiles action');
  console.log(`PASS on Rex ${JSON.parse(rex('whoami','--json')).rex_version}`);
} finally {
  if(session) await c.call('session.destroy',{session_id:session});
  c.close();
}

// fakeReload is a rex executable for the config reload. It records each call in calls. With the file
// block, it writes its pid and execs sleep, so the process that the hub starts is the one that
// blocks, and no child keeps its output pipes. With the file fail, the reload fails.
type fakeReload struct{ dir, bin string }

func newFakeReload(t *testing.T) *fakeReload {
	t.Helper()
	dir := t.TempDir()
	f := &fakeReload{dir: dir, bin: filepath.Join(dir, "rex")}
	script := "#!/bin/sh\n" +
		"echo \"$*\" >> '" + dir + "/calls'\n" +
		"if [ -f '" + dir + "/block' ]; then rm '" + dir + "/block'; echo $$ > '" + dir + "/pid'; exec sleep 30; fi\n" +
		"if [ -f '" + dir + "/fail' ]; then echo 'reload failed'; exit 1; fi\n" +
		"echo reloaded\n"
	if err := os.WriteFile(f.bin, []byte(script), 0o755); err != nil {
		t.Fatal(err)
	}
	return f
}

func (f *fakeReload) set(t *testing.T, name string, on bool) {
	t.Helper()
	p := filepath.Join(f.dir, name)
	if !on {
		os.Remove(p)
		return
	}
	if err := os.WriteFile(p, nil, 0o644); err != nil {
		t.Fatal(err)
	}
}

// calls is the number of reloads that started.
func (f *fakeReload) calls() int {
	b, _ := os.ReadFile(filepath.Join(f.dir, "calls"))
	return strings.Count(string(b), "config reload")
}

// paletteTestHub is a hub with the palette tables, its palette file path in dir (not written),
// and fake as its rex. db and events are in their own directory.
func paletteTestHub(t *testing.T, db *DB, dir string, fake *fakeReload) *Hub {
	t.Helper()
	ev, err := openEvents(filepath.Join(t.TempDir(), "events.jsonl"))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { ev.f.Close() })
	return &Hub{db: db, ev: ev, rexBinary: fake.bin, paletteKick: make(chan struct{}, 1),
		cfg: Config{PaletteLua: filepath.Join(dir, "lazyrex_palette.lua"), Server: "unix:///nonexistent/rex.sock"}}
}

func paletteTestDB(t *testing.T) *DB {
	t.Helper()
	db, err := openDB(filepath.Join(t.TempDir(), "hub.db"))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { db.Close() })
	for _, s := range []string{uiSchema, formSchema} {
		if _, err := db.Exec(s); err != nil {
			t.Fatal(err)
		}
	}
	return db
}

func paletteLoadedRow(t *testing.T, db *DB) string {
	t.Helper()
	var v string
	db.QueryRow(`SELECT value FROM ui_state WHERE key = 'palette_loaded'`).Scan(&v)
	return v
}

func readPalette(t *testing.T, h *Hub) string {
	t.Helper()
	b, err := os.ReadFile(h.cfg.PaletteLua)
	if errors.Is(err, os.ErrNotExist) {
		return "<missing>"
	}
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// paletteEvents gives the palette_written events, as raw lines.
func paletteEvents(t *testing.T, h *Hub) []string {
	t.Helper()
	b, _ := os.ReadFile(h.ev.f.Name())
	var out []string
	for _, l := range strings.Split(string(b), "\n") {
		if strings.Contains(l, `"event":"palette_written"`) {
			out = append(out, l)
		}
	}
	return out
}

func paletteWait(t *testing.T, what string, ok func() bool) {
	t.Helper()
	for end := time.Now().Add(10 * time.Second); time.Now().Before(end); time.Sleep(20 * time.Millisecond) {
		if ok() {
			return
		}
	}
	t.Fatalf("timed out waiting for %s", what)
}

// lockedLog takes the log output of the hub's goroutines for one test.
type lockedLog struct {
	mu sync.Mutex
	b  bytes.Buffer
}

func (l *lockedLog) Write(p []byte) (int, error) {
	l.mu.Lock()
	defer l.mu.Unlock()
	return l.b.Write(p)
}

func (l *lockedLog) String() string {
	l.mu.Lock()
	defer l.mu.Unlock()
	return l.b.String()
}

func captureLog(t *testing.T) *lockedLog {
	l := &lockedLog{}
	log.SetOutput(l)
	t.Cleanup(func() { log.SetOutput(os.Stderr) })
	return l
}

// The stop file is the header of every palette file, and it declares no entry.
func TestPaletteHeader(t *testing.T) {
	full := paletteLua(map[string][]paletteCommand{"p": {{ID: "go", Title: "Go", Route: "r"}}})
	if !strings.HasPrefix(full, paletteHeader) || !strings.HasPrefix(paletteLua(nil), paletteHeader) {
		t.Fatalf("a palette file does not start with the header:\n%s", full)
	}
	if strings.Contains(paletteHeader, "rex.action") || strings.Contains(paletteHeader, "local function") ||
		strings.Count(paletteHeader, "\n") != 2 || !strings.HasPrefix(paletteHeader, "-- Generated by the LazyRex hub.") {
		t.Fatalf("the header is not two comment lines:\n%s", paletteHeader)
	}
}

// Start, change and stop: the loop writes the full file and reloads; a plugin's new commands
// rewrite it; the stop leaves the header alone, reloads, and records it. After the stop, a kick
// changes nothing, and a second stop does nothing.
func TestPaletteStop(t *testing.T) {
	fake := newFakeReload(t)
	db := paletteTestDB(t)
	h := paletteTestHub(t, db, t.TempDir(), fake)
	h.startPalette()
	paletteWait(t, "the first write", func() bool { return fake.calls() == 1 && paletteLoadedRow(t, db) != "" })
	if got := readPalette(t, h); got != paletteLua(nil) {
		t.Fatalf("after the start:\n%s", got)
	}

	h.entries = []*configEntry{{name: "p"}}
	h.saveCommands(context.Background(), "p", []paletteCommand{{ID: "go", Title: "Go", Route: "r"}})
	want := paletteLua(map[string][]paletteCommand{"p": {{ID: "go", Title: "Go", Route: "r"}}})
	paletteWait(t, "the change", func() bool { return fake.calls() == 2 && paletteLoadedRow(t, db) == want })
	if got := readPalette(t, h); got != want {
		t.Fatalf("after the change:\n%s", got)
	}

	h.paletteStop()
	if got := readPalette(t, h); got != paletteHeader {
		t.Fatalf("after the stop:\n%s", got)
	}
	evs := paletteEvents(t, h)
	if fake.calls() != 3 || paletteLoadedRow(t, db) != paletteHeader || len(evs) != 3 ||
		!strings.Contains(evs[2], `"stop":true`) || !strings.Contains(evs[2], `"reload_ok":true`) || strings.Contains(evs[1], `"stop"`) {
		t.Fatalf("after the stop: %d reloads, palette_loaded %q, events %v", fake.calls(), paletteLoadedRow(t, db), evs)
	}

	h.saveCommands(context.Background(), "p", []paletteCommand{{ID: "other", Title: "Other", Route: "r"}})
	h.kickPalette()
	time.Sleep(time.Second)
	h.paletteStop()
	if got := readPalette(t, h); got != paletteHeader || fake.calls() != 3 || len(paletteEvents(t, h)) != 3 {
		t.Fatalf("a kick and a stop after the stop changed something: %d reloads\n%s", fake.calls(), got)
	}
}

// A stop during a normal reload that blocks: the stop cancels it (the rex process is gone), writes
// the stop file and reloads, within its two bounds.
func TestPaletteStopCancelsReload(t *testing.T) {
	fake := newFakeReload(t)
	fake.set(t, "block", true)
	db := paletteTestDB(t)
	h := paletteTestHub(t, db, t.TempDir(), fake)
	h.startPalette()
	pidFile := filepath.Join(fake.dir, "pid")
	paletteWait(t, "the blocked reload", func() bool { _, err := os.Stat(pidFile); return err == nil })
	b, _ := os.ReadFile(pidFile)
	pid, err := strconv.Atoi(strings.TrimSpace(string(b)))
	if err != nil {
		t.Fatal(err)
	}
	if got := readPalette(t, h); got != paletteLua(nil) {
		t.Fatalf("before the stop:\n%s", got)
	}

	began := time.Now()
	h.paletteStop()
	took := time.Since(began)
	t.Logf("paletteStop took %v", took)
	if took > paletteStopJoin+paletteStopReload {
		t.Errorf("the stop took %v", took)
	}
	if err := syscall.Kill(pid, 0); !errors.Is(err, syscall.ESRCH) {
		t.Errorf("the blocked rex %d still runs: %v", pid, err)
	}
	evs := paletteEvents(t, h)
	if got := readPalette(t, h); got != paletteHeader || fake.calls() != 2 || len(evs) != 2 ||
		!strings.Contains(evs[1], `"stop":true`) || !strings.Contains(evs[1], `"reload_ok":true`) || paletteLoadedRow(t, db) != paletteHeader {
		t.Fatalf("after the stop: %d reloads, events %v\n%s", fake.calls(), evs, got)
	}
}

// A loop that hangs before it publishes: the stop waits paletteStopJoin, logs, and leaves the
// file. When the hang ends, the cancelled write publishes nothing and starts no reload.
func TestPaletteStopLoopHangs(t *testing.T) {
	logs := captureLog(t)
	fake := newFakeReload(t)
	dir := t.TempDir()
	h := paletteTestHub(t, paletteTestDB(t), dir, fake)
	entered, release := make(chan struct{}), make(chan struct{})
	var once sync.Once
	h.paletteHook = func() {
		once.Do(func() { close(entered) })
		<-release
	}
	h.startPalette()
	<-entered

	began := time.Now()
	h.paletteStop()
	took := time.Since(began)
	if took < paletteStopJoin || took > paletteStopJoin+time.Second {
		t.Errorf("the stop took %v, want about %v", took, paletteStopJoin)
	}
	if !strings.Contains(logs.String(), "palette: the palette write did not end; not rewritten at stop") {
		t.Errorf("log: %s", logs.String())
	}
	close(release)
	select {
	case <-h.paletteDone:
	case <-time.After(5 * time.Second):
		t.Fatal("the loop did not end after the release")
	}
	time.Sleep(200 * time.Millisecond)
	ents, _ := os.ReadDir(dir)
	if got := readPalette(t, h); got != "<missing>" || fake.calls() != 0 || len(ents) != 0 || len(paletteEvents(t, h)) != 0 {
		t.Fatalf("the cancelled write: %d reloads, dir %v\n%s", fake.calls(), ents, got)
	}
}

// Another writer changed the file after this hub wrote it: the stop leaves it and logs.
func TestPaletteStopAnotherWriter(t *testing.T) {
	logs := captureLog(t)
	fake := newFakeReload(t)
	h := paletteTestHub(t, paletteTestDB(t), t.TempDir(), fake)
	h.startPalette()
	paletteWait(t, "the first write", func() bool { return fake.calls() == 1 })
	if err := os.WriteFile(h.cfg.PaletteLua, []byte("-- another hub\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	h.paletteStop()
	if got := readPalette(t, h); got != "-- another hub\n" || fake.calls() != 1 ||
		!strings.Contains(logs.String(), "palette: another writer changed the file; not rewritten at stop") {
		t.Fatalf("%d reloads, log %q\n%s", fake.calls(), logs.String(), got)
	}
}

// A failed reload at stop: the stop file stays, the event says so, palette_loaded keeps the
// full content, and there is no retry.
func TestPaletteStopReloadFails(t *testing.T) {
	fake := newFakeReload(t)
	db := paletteTestDB(t)
	h := paletteTestHub(t, db, t.TempDir(), fake)
	h.startPalette()
	paletteWait(t, "the first write", func() bool { return fake.calls() == 1 && paletteLoadedRow(t, db) != "" })
	fake.set(t, "fail", true)
	h.paletteStop()
	time.Sleep(time.Second)
	evs := paletteEvents(t, h)
	if got := readPalette(t, h); got != paletteHeader || fake.calls() != 2 || len(evs) != 2 ||
		!strings.Contains(evs[1], `"stop":true`) || !strings.Contains(evs[1], `"reload_ok":false`) || paletteLoadedRow(t, db) != paletteLua(nil) {
		t.Fatalf("%d reloads, events %v, palette_loaded %q\n%s", fake.calls(), evs, paletteLoadedRow(t, db), got)
	}
}

// After a stop whose reload failed, the next start writes the full file again: palette_loaded
// still names the full content, but the file holds the header.
func TestPaletteStopReloadFailsThenStart(t *testing.T) {
	fake := newFakeReload(t)
	db, dir := paletteTestDB(t), t.TempDir()
	h := paletteTestHub(t, db, dir, fake)
	h.startPalette()
	paletteWait(t, "the first write", func() bool { return fake.calls() == 1 && paletteLoadedRow(t, db) != "" })
	fake.set(t, "fail", true)
	h.paletteStop()
	fake.set(t, "fail", false)

	h2 := paletteTestHub(t, db, dir, fake)
	h2.startPalette()
	defer h2.paletteStop()
	<-h2.paletteTried
	if got := readPalette(t, h2); got != paletteLua(nil) || fake.calls() != 3 {
		t.Fatalf("the next start: %d reloads\n%s", fake.calls(), got)
	}
}

// The start skips the write and the reload only when palette_loaded and the file both hold the
// content. Equal bytes on disk alone do not prove a reload.
func TestPaletteStartChecksDisk(t *testing.T) {
	full := paletteLua(nil)
	for _, tc := range []struct {
		name, loaded, file string
		write              bool
		reloads            int
	}{
		{"stop file on disk", full, paletteHeader, true, 1},
		{"no file", full, "", true, 1},
		{"both equal", full, full, false, 0},
		{"not reloaded", paletteHeader, full, false, 1},
	} {
		t.Run(tc.name, func(t *testing.T) {
			fake := newFakeReload(t)
			db := paletteTestDB(t)
			h := paletteTestHub(t, db, t.TempDir(), fake)
			if _, err := db.Exec(`INSERT INTO ui_state (key, value) VALUES ('palette_loaded', ?)`, tc.loaded); err != nil {
				t.Fatal(err)
			}
			if tc.file != "" {
				if err := os.WriteFile(h.cfg.PaletteLua, []byte(tc.file), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			before, _ := os.Stat(h.cfg.PaletteLua)
			h.startPalette()
			<-h.paletteTried
			after, _ := os.Stat(h.cfg.PaletteLua)
			wrote := before == nil || !os.SameFile(before, after)
			if got := readPalette(t, h); got != full || wrote != tc.write || fake.calls() != tc.reloads {
				t.Errorf("wrote %v, %d reloads\n%s", wrote, fake.calls(), got)
			}
			h.paletteStop()
		})
	}
}

// A failed write keeps the old file: at the start (no stop write follows, because this hub never
// put its content in the file), and at the stop (no reload follows).
func TestPaletteWriteFails(t *testing.T) {
	if os.Geteuid() == 0 {
		t.Skip("root writes into a read-only directory")
	}
	t.Run("start", func(t *testing.T) {
		fake := newFakeReload(t)
		dir := t.TempDir()
		h := paletteTestHub(t, paletteTestDB(t), dir, fake)
		os.WriteFile(h.cfg.PaletteLua, []byte("-- old\n"), 0o644)
		os.Chmod(dir, 0o555)
		defer os.Chmod(dir, 0o755)
		h.startPalette()
		<-h.paletteTried
		h.paletteStop()
		if got := readPalette(t, h); got != "-- old\n" || fake.calls() != 0 {
			t.Fatalf("%d reloads\n%s", fake.calls(), got)
		}
	})
	t.Run("stop", func(t *testing.T) {
		logs := captureLog(t)
		fake := newFakeReload(t)
		dir := t.TempDir()
		h := paletteTestHub(t, paletteTestDB(t), dir, fake)
		h.startPalette()
		paletteWait(t, "the first write", func() bool { return fake.calls() == 1 })
		os.Chmod(dir, 0o555)
		defer os.Chmod(dir, 0o755)
		h.paletteStop()
		if got := readPalette(t, h); got != paletteLua(nil) || fake.calls() != 1 || !strings.Contains(logs.String(), "not rewritten at stop") {
			t.Fatalf("%d reloads, log %q\n%s", fake.calls(), logs.String(), got)
		}
	})
}

// No stop write without a palette file in the config, or for a hub whose loop never started.
func TestPaletteNeverWritten(t *testing.T) {
	fake := newFakeReload(t)
	h := paletteTestHub(t, paletteTestDB(t), t.TempDir(), fake)
	h.paletteStop() // the loop never started
	h.cfg.PaletteLua = ""
	h2 := paletteTestHub(t, paletteTestDB(t), t.TempDir(), fake)
	h2.cfg.PaletteLua = ""
	h2.startPalette()
	<-h2.paletteTried
	h2.paletteStop()
	if fake.calls() != 0 {
		t.Fatalf("%d reloads", fake.calls())
	}
}

// After a crash (no stop), palette_loaded and the file can name an older run: the start writes
// and reloads the full file.
func TestPaletteStartAfterCrash(t *testing.T) {
	fake := newFakeReload(t)
	db := paletteTestDB(t)
	h := paletteTestHub(t, db, t.TempDir(), fake)
	stale := paletteLua(map[string][]paletteCommand{"gone": {{ID: "x", Title: "X", Route: "r"}}})
	db.Exec(`INSERT INTO ui_state (key, value) VALUES ('palette_loaded', ?)`, stale)
	os.WriteFile(h.cfg.PaletteLua, []byte(stale), 0o644)
	h.startPalette()
	defer h.paletteStop()
	<-h.paletteTried
	if got := readPalette(t, h); got != paletteLua(nil) || fake.calls() != 1 || paletteLoadedRow(t, db) != paletteLua(nil) {
		t.Fatalf("%d reloads\n%s", fake.calls(), got)
	}
}

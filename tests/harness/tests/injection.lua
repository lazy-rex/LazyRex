-- Injections commit a concurrent write before the plugin's matching batch.
test('an injection matches only its key and is consumed once', function()
  local a = agent('alice')
  a:call('fix.put', {key = 'other', value = 1})
  with_injection({match = {writes = 'target'}, ops = {{key = 'side', value = 'injected'}}}, 1, function()
    a:call('fix.put', {key = 'unrelated', value = 1})
    a:call('fix.put', {key = 'target', value = 2})
  end)
  expect(store('side').value).to_be('injected')
end)

test('replay commits the same batch first', function()
  local before = batches()
  with_injection({match = {writes = 'twice'}, replay = true}, 1, function()
    agent('alice'):call('fix.put', {key = 'twice', value = 'x'})
  end)
  expect(store('twice').value).to_be('x')
  expect(batches() - before).to_be(1)
end)

test('advance_rev moves the revision counter forward only', function()
  expect(advance_rev('9007199254740992')).to_be('9007199254740992')
  agent('alice'):call('fix.put', {key = 'after', value = 1})
  expect(store('after').rev).to_be('9007199254740993')
  expect(advance_rev('5')).to_be('9007199254740993')
end)

test('fail fails the matching batch after its ops commit', function()
  local a = agent('alice')
  with_injection({match = {writes = 'refused'}, ops = {{key = 'before_fail', value = 'kept'}}, fail = 'injected crash'}, 1, function()
    expect_error(function() a:call('fix.put', {key = 'refused', value = 1}) end, 'injected crash')
  end)
  expect(store('refused').rev).to_be('0')
  expect(store('before_fail').value).to_be('kept')
  a:call('fix.put', {key = 'refused', value = 2})
  expect(store('refused').value).to_be(2)
end)

test('write commits and deletes records now', function()
  write({{key = 'w1', value = {n = 1}}, {key = 'w2', value = 'two'}})
  expect(store('w1').value).to_equal({n = 1})
  expect(agent('alice'):call('fix.get', {key = 'w2'}).value).to_be('two')
  write({{key = 'w1', delete = true}})
  expect(store('w1').rev).to_be('0')
  expect_error(function() write({}) end, 'nonempty')
end)

test('put_operation saves an operation that the plugin reads', function()
  put_operation({key = 'legacy/op', fingerprint = 'fp-v1', result = {id = 'old'}})
  local op = agent('alice'):call('fix.op', {key = 'legacy/op'})
  expect(op.found).to_be(true)
  expect(op.fingerprint).to_be('fp-v1')
  expect(op.result).to_equal({id = 'old'})
end)

test('updates matches a change of a read record, not its creation', function()
  local a = agent('alice')
  with_injection({match = {updates = 'upd'}, fail = 'injected update failure'}, 1, function()
    a:call('fix.put', {key = 'upd', value = 1, if_rev = '0'})
    local rev = store('upd').rev
    expect_error(function() a:call('fix.put', {key = 'upd', value = 2, if_rev = rev}) end, 'injected update failure')
  end)
  expect(store('upd').value).to_be(1)
end)

test('cancel_injection ends an injection that has no end', function()
  local a = agent('alice')
  local id = inject({match = {writes = 'held'}, fail = 'held', times = 'always'})
  expect_error(function() a:call('fix.put', {key = 'held', value = 1}) end, 'held')
  expect_error(function() a:call('fix.put', {key = 'held', value = 2}) end, 'held')
  expect(cancel_injection(id).consumed).to_be(2)
  a:call('fix.put', {key = 'held', value = 3})
  expect(store('held').value).to_be(3)
  expect(injection(id).consumed).to_be(2)
end)

test('skip lets the first matching batches pass', function()
  local a = agent('alice')
  with_injection({match = {writes = 'skipped'}, skip = 2, fail = 'third write'}, 1, function()
    a:call('fix.put', {key = 'skipped', value = 1})
    a:call('fix.put', {key = 'skipped', value = 2})
    expect_error(function() a:call('fix.put', {key = 'skipped', value = 3}) end, 'third write')
  end)
  expect(store('skipped').value).to_be(2)
end)

test('cancel_injection takes an exact id', function()
  local id = inject({match = {writes = 'exact-cancel'}, fail = 'cancelled later', times = 'always'})
  expect_error(function() cancel_injection(id + 0.5) end, 'no injection')
  expect(injection(id).remaining).to_be('always')
  expect(cancel_injection(id).consumed).to_be(0)
end)

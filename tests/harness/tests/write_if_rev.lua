-- write() with if_rev: a test that reads a record and writes it back must not overwrite a newer
-- commit. A stale if_rev fails with the code conflict and commits nothing.

test('a stale if_rev conflicts, and the newer value stays', function()
  write({{key = 'ifrev/a', value = 'old'}})
  local read = store('ifrev/a')
  write({{key = 'ifrev/a', value = 'newer'}}) -- another writer commits in between
  local newer = store('ifrev/a')
  local e = expect_error(function() write({{key = 'ifrev/a', value = 'stale', if_rev = read.rev}}) end)
  expect(e.code).to_be('conflict')
  expect(e.message).to_match('ifrev/a is at rev ' .. newer.rev)
  expect(store('ifrev/a')).to_equal(newer)
end)

test('a batch with a conflict in its second op commits nothing', function()
  write({{key = 'ifrev/b1', value = 1}, {key = 'ifrev/b2', value = 1}})
  local b1, b2 = store('ifrev/b1'), store('ifrev/b2')
  write({{key = 'ifrev/b2', value = 2}})
  local e = expect_error(function()
    write({{key = 'ifrev/b1', value = 3, if_rev = b1.rev}, {key = 'ifrev/b2', value = 3, if_rev = b2.rev}})
  end)
  expect(e.code).to_be('conflict')
  expect(store('ifrev/b1')).to_equal(b1)
  expect(store('ifrev/b2').value).to_be(2)
end)

test('a write with the current rev commits', function()
  write({{key = 'ifrev/c', value = 'one'}})
  local cur = store('ifrev/c')
  write({{key = 'ifrev/c', value = 'two', if_rev = cur.rev}})
  local after = store('ifrev/c')
  expect(after.value).to_be('two')
  expect(after.rev).not_to_be(cur.rev)
end)

test('if_rev 0 creates an absent record and conflicts on a present one', function()
  expect(store('ifrev/d')).to_equal({rev = '0'})
  write({{key = 'ifrev/d', value = 'created', if_rev = '0'}})
  expect(store('ifrev/d').value).to_be('created')
  local e = expect_error(function() write({{key = 'ifrev/d', value = 'again', if_rev = '0'}}) end)
  expect(e.code).to_be('conflict')
  expect(store('ifrev/d').value).to_be('created')
end)

test('a write without if_rev still overwrites', function()
  write({{key = 'ifrev/e', value = 'first'}})
  write({{key = 'ifrev/e', value = 'second'}})
  expect(store('ifrev/e').value).to_be('second')
end)
